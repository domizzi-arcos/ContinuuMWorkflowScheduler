"""LaTeX outputs: numbers.tex (one \\newcommand per cited number) and
booktabs tables. Numbers are formatted here, once; the paper never retypes
them.

Macro naming: \\<Quantity><Metric><Policy>, letters only, e.g.
\\RatioCostMinCost (geometric-mean cost ratio min_cost / topsis),
\\CIlowCostMinCost, \\PholmCostMinCost, \\WinsCostBestFit,
\\MeanCostTopsis. Policy names are CamelCased with digits spelled out
(topsis_u0 -> TopsisUZero).
"""

from __future__ import annotations

import os

import pandas as pd

import algorithms
import stats

DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
          "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def camel(name: str) -> str:
    """policy/metric name -> letters-only CamelCase usable in a macro name."""
    parts = []
    for part in name.split("_"):
        word = "".join(DIGITS.get(ch, ch) for ch in part)
        parts.append(word[:1].upper() + word[1:])
    return "".join(parts)


def fmt(x: float, metric: str | None = None) -> str:
    """Display format per quantity; kept here so tables and macros agree."""
    if pd.isna(x):
        return "--"
    if metric == "cost":
        return f"{x:.4f}"
    if metric == "energy":
        return f"{x:.2f}"
    if metric == "makespan":
        return f"{x:,.0f}".replace(",", "{,}")
    return f"{x:.2f}"


def fmt_p(p: float) -> str:
    if pd.isna(p):
        return "--"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def numbers_tex(runs: pd.DataFrame, normalised: pd.DataFrame, tests: pd.DataFrame,
                win: pd.DataFrame) -> str:
    lines = ["% Generated by scripts/analysis; do not edit by hand."]

    def cmd(name: str, value: str):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    gm = stats.grand_mean(runs)
    for a in algorithms.ordered(gm.index):
        for m in stats.METRICS:
            cmd(f"Mean{camel(m)}{camel(a)}", fmt(gm.loc[a, m], m))
    for _, r in normalised.iterrows():
        k = f"{camel(r.metric)}{camel(r.algorithm)}"
        cmd(f"Ratio{k}", f"{r.geomean_ratio:.2f}")
        cmd(f"CIlow{k}", f"{r.ci_low:.2f}")
        cmd(f"CIhigh{k}", f"{r.ci_high:.2f}")
    for _, r in tests.iterrows():
        k = f"{camel(r.metric)}{camel(r.algorithm)}"
        cmd(f"Pholm{k}", fmt_p(r.p_holm))
        cmd(f"RefBetter{k}", str(int(r.ref_better)))
        cmd(f"Npairs{k}", str(int(r.n)))
    for a in win.index:
        for m in stats.METRICS:
            cmd(f"Wins{camel(m)}{camel(a)}", str(int(win.loc[a, f"{m}_wins"])))
            cmd(f"Ties{camel(m)}{camel(a)}", str(int(win.loc[a, f"{m}_ties"])))
    cmd("NumRuns", str(len(runs)))
    cmd("NumConfigs", str(len(runs.groupby(stats._config_cols(runs), dropna=False))))
    cmd("NumSeeds", str(runs["seed"].nunique()))
    return "\n".join(lines) + "\n"


def tab_results(runs: pd.DataFrame, win: pd.DataFrame) -> str:
    gm = stats.grand_mean(runs)
    ts = stats.tier_share(runs)
    rows = [r"\begin{tabular}{lrrrcc}", r"\toprule",
            r"Policy & Makespan (ms) & Cost (\$) & Energy (Wh) & Wins C/E/M & Edge/Fog/Cloud (\%) \\", r"\midrule"]
    for a in algorithms.ordered(gm.index):
        w = "/".join(str(int(win.loc[a, f"{m}_wins"])) for m in ("cost", "energy", "makespan"))
        share = " / ".join(f"{ts.loc[a, f'share_{t}_mean']:.0f}$\\pm${ts.loc[a, f'share_{t}_std']:.0f}"
                           if not pd.isna(ts.loc[a, f"share_{t}_std"]) else f"{ts.loc[a, f'share_{t}_mean']:.0f}"
                           for t in stats.TIERS)
        rows.append(f"{algorithms.label(a)} & {fmt(gm.loc[a, 'makespan'], 'makespan')} & "
                    f"{fmt(gm.loc[a, 'cost'], 'cost')} & {fmt(gm.loc[a, 'energy'], 'energy')} & {w} & {share} \\\\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(rows) + "\n"


def tab_tiers(per_tier: pd.DataFrame) -> str:
    rows = [r"\begin{tabular}{llrrr}", r"\toprule", r"Policy & Tier & Tasks & Cost (\$) & Energy (Wh) \\", r"\midrule"]
    for a in algorithms.ordered(per_tier["algorithm"].unique()):
        g = per_tier[per_tier.algorithm == a].set_index("server_type")
        for i, t in enumerate(stats.TIERS):
            if t not in g.index:
                continue
            r = g.loc[t]
            name = algorithms.label(a) if i == 0 else ""
            rows.append(f"{name} & {t.capitalize()} & {int(r.tasks)} & {r.cost_usd:.4f} & {r.energy_wh:.2f} \\\\")
        rows.append(r"\addlinespace")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(rows) + "\n"


def tab_stats(normalised: pd.DataFrame, tests: pd.DataFrame) -> str:
    rows = [r"\begin{tabular}{llrcrrr}", r"\toprule",
            r"Metric & Policy & Ratio to TOPSIS & 95\% CI & TOPSIS better & $n$ & $p_{\mathrm{Holm}}$ \\", r"\midrule"]
    t = tests.set_index(["metric", "algorithm"]) if not tests.empty else None
    for m in stats.METRICS:
        nm = normalised[(normalised.metric == m) & (normalised.algorithm != stats.REF)]
        for i, a in enumerate(algorithms.ordered(nm["algorithm"])):
            r = nm[nm.algorithm == a].iloc[0]
            tr = t.loc[(m, a)] if t is not None and (m, a) in t.index else None
            rows.append(f"{m.capitalize() if i == 0 else ''} & {algorithms.label(a)} & {r.geomean_ratio:.2f} & "
                        f"[{r.ci_low:.2f}, {r.ci_high:.2f}] & "
                        f"{int(tr.ref_better) if tr is not None else '--'} & {int(tr.n) if tr is not None else '--'} & "
                        f"{fmt_p(tr.p_holm) if tr is not None else '--'} \\\\")
        rows.append(r"\addlinespace")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(rows) + "\n"


def write_all(out_dir: str, runs, normalised, tests, win, per_tier) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    files = {
        "numbers.tex": numbers_tex(runs, normalised, tests, win),
        "tab_results.tex": tab_results(runs, win),
        "tab_tiers.tex": tab_tiers(per_tier),
        "tab_stats.tex": tab_stats(normalised, tests),
    }
    paths = []
    for name, text in files.items():
        path = os.path.join(out_dir, name)
        with open(path, "w") as f:
            f.write(text)
        paths.append(path)
    return paths
